    assert abs(calc.get_average() - 1.5) < 1e-10

    calc.add_number(3)
    assert abs(calc.get_average() - 2.0) < 1e-10

    # Test with buffer full (cycling): now we have 4,2,3
    calc.add_number(4)
    assert abs(calc.get_average() - 3.0) < 1e-10

