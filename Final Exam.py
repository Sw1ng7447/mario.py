class RingBuffer:
    def __init__(self, size):
        self.size = size
        self.buffer = [None] * size  # Preallocate list with None values
        self.current = 0  # Position to write next item
        self.is_filled = False  # Track if the buffer has been completely filled

    def add(self, value):
        """Add a new value to the buffer, overwriting the oldest when full."""
        self.buffer[self.current] = value
        self.current = (self.current + 1) % self.size  # Circular indexing
        if self.current == 0:
            self.is_filled = True  # Buffer has completed one full cycle

    def get_inorder(self):
        """Return values in the order they were added."""
        if not self.is_filled:
            return [x for x in self.buffer[:self.current] if x is not None]
        return self.buffer[self.current:] + self.buffer[:self.current]

    def get_all(self):
        """Return all current values in the buffer."""
        if not self.is_filled:
            return [x for x in self.buffer[:self.current] if x is not None]
        return self.buffer

    def is_full(self):
        """Return True if the buffer is full."""
        return self.is_filled

    def current_size(self):
        """Return the number of elements currently in the buffer."""
        return self.size if self.is_filled else self.current

